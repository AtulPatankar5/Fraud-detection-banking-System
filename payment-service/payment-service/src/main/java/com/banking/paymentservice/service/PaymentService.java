package com.banking.paymentservice.service;

import com.banking.paymentservice.dto.CreatePaymentRequest;
import com.banking.paymentservice.dto.PaymentOrderResponse;
import com.banking.paymentservice.entity.*;
import com.banking.paymentservice.exception.BusinessException;
import com.banking.paymentservice.exception.ErrorCode;
import com.banking.paymentservice.repository.OutboxEventRepository;
import com.banking.paymentservice.repository.PaymentRepository;
import com.banking.paymentservice.repository.WebhookEventRepository;
import com.banking.paymentservice.security.WebhookSignatureVerifier;
import com.razorpay.Order;
import com.razorpay.RazorpayClient;
import com.razorpay.RazorpayException;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.json.JSONObject;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.HashMap;
import java.util.Map;
import java.util.UUID;

/**
 *
 * /*
 * PAYMENT SERVICE - RAZORPAY INTEGRATION
 * <p>
 * This service handles the complete payment lifecycle.
 * <p>
 * 1. Create an internal payment record in our database.
 * 2. Ask Razorpay to create a payment order.
 * 3. Save the Razorpay Order ID in our database.
 * 4. Send the Order ID to the frontend.
 * 5. Frontend opens Razorpay Checkout for the customer.
 * 6. Customer completes payment using UPI / Card / Net Banking.
 * 7. Razorpay returns Payment ID, Order ID and Signature.
 * 8. Backend verifies the signature and confirms payment status.
 * 9. Update our database with the final payment status.
 * 10. Webhook handles payment updates if frontend callback fails.
 * <p>
 * IMPORTANT:
 * - Transaction ID is generated by our application.
 * - Razorpay Order ID is generated by Razorpay before payment.
 * - Razorpay Payment ID identifies an actual payment attempt.
 * - Creating an order does NOT mean payment is successful.
 */

@Service
@Slf4j
@RequiredArgsConstructor
public class PaymentService {

    private final PaymentRepository paymentRepository;

    private final WebhookSignatureVerifier signatureVerifier;

    private final WebhookEventRepository webhookEventRepository;

    private final ObjectMapper objectMapper;

    private final OutboxEventRepository outboxEventRepository;

    @Value("${razorpay.key-id}")
    private String keyId;

    @Value("${razorpay.key-secret}")
    private String keySecret;

    private static final String PAYMENT_COMPLETED_TOPIC = "payment.completed";
    private static final String PAYMENT_FAILED_TOPIC = "payment.failed";

    /**
     * Create RazorPay payment order
     * <p>
     * FLOW
     * 1. Create Order in razorPay
     * 2. Save Payment record in DB
     * 3. Return order details to frontend
     * 4. Frontend Shows razorpay checkout pay
     * 5. User pays
     * 6. razorpay calls webhooks
     * <p>
     * <p>
     * <p>
     * /*
     * STEP 2: CREATE ORDER IN RAZORPAY
     * <p>
     * Our backend sends a request to Razorpay asking it
     * to create a payment order.
     * <p>
     * We send:
     * - Amount
     * - Currency (INR)
     * - Receipt (our internal transaction reference)
     * <p>
     * IMPORTANT:
     * Razorpay expects the amount in PAISE, not RUPEES.
     * <p>
     * Example:
     * 5000 INR * 100 = 500000 PAISE
     * <p>
     * Razorpay generates and returns an Order ID.
     * <p>
     * Example:
     * order_ABC123
     * <p>
     * This Order ID represents the payment request.
     * It does NOT mean the customer has completed payment.
     *
     * @param request
     * @return
     */
    public PaymentOrderResponse createOrder(CreatePaymentRequest request) {

        log.info("Creating payment order for account : {} amount {}",
                request.getAccountNumber(), request.getAmount());

        try {

            RazorpayClient razorpayClient = new RazorpayClient(keyId, keySecret);

            // Converted amount
            int convertedAmount = request.getAmount().multiply(BigDecimal.valueOf(100)).intValueExact();

            // 1. Create Order in razorPay
            JSONObject orderRequest = new JSONObject();
            orderRequest.put("amount", convertedAmount);
            orderRequest.put("currency", "USD");
            orderRequest.put("receipt", "rcpt_" + System.currentTimeMillis()
                    + UUID.randomUUID().toString().replace("-", "").substring(0, 10));

            Order razorpayOrder = razorpayClient.orders.create(orderRequest);

            log.info("Razorpay order created : {}", razorpayOrder.get("id").toString());

            // 2. Save Payment record in DB
            /**
             *
             * /*
             * STEP 3: SAVE RAZORPAY ORDER DETAILS
             *
             * After Razorpay successfully creates the order,
             * we receive its Order ID.
             *
             * We save this Order ID in our Payment table.
             *
             * Example:
             * razorpayOrderId = order_ABC123
             * status = CREATED
             *
             * Why save it?
             * We need this Order ID later to:
             * - Open Razorpay Checkout.
             * - Verify the payment response.
             * - Identify the payment when a webhook arrives.
             *
             * CREATED means the order exists.
             * It does NOT mean money has been received.
             */

            Payment payment = new Payment();
            payment.setRazorpayOrderId(razorpayOrder.get("id").toString());
            payment.setAccountNumber(request.getAccountNumber());
            payment.setAmount(request.getAmount());
            payment.setCurrency("USD");
            payment.setStatus(PaymentStatus.CREATED);
            payment.setDescription(request.getDescription());

            Payment savedPayment = paymentRepository.save(payment);

            return mapToResponse(savedPayment, razorpayOrder);
        } catch (RazorpayException exception) {

            log.error("Razorpay order creation failed", exception);

            throw new BusinessException(
                    ErrorCode.PAYMENT_PROVIDER_ERROR,
                    "Unable to create payment order with payment provider");
        } catch (ArithmeticException e) {
            throw new BusinessException(
                    ErrorCode.INVALID_REQUEST,
                    "Payment amount exceeds the supported range or precision");
        }
    }

    private PaymentOrderResponse mapToResponse(Payment savedPayment, Order razorPayOrder) {
        return new PaymentOrderResponse(
                savedPayment.getId(),
                razorPayOrder.get("id").toString(),
                savedPayment.getAmount(),
                "USD",
                "CREATED",
                keyId);

    }

    // 6. razorpay calls webhooks
    @Transactional
    public void handleWebhook(
            byte[] rawBody,
            String signature,
            String eventId) {

        // 1. Verify signature BEFORE parsing JSON
        signatureVerifier.verifySignature(rawBody, signature);

        if (eventId == null || eventId.isBlank()) {
            throw new BusinessException(
                    ErrorCode.WEBHOOK_EVENT_INVALID,
                    "Webhook event ID is missing");
        }

        try {

            // 2. Parse only after signature verification
            JsonNode root = objectMapper.readTree(rawBody);

            String eventType = root.path("event").asText(null);

            if (eventType == null || eventType.isBlank()) {
                throw new BusinessException(
                        ErrorCode.WEBHOOK_EVENT_INVALID,
                        "Webhook event type is missing");
            }

            // 3. Check duplicate event
            if (webhookEventRepository.existsByEventId(eventId)) {
                log.info("Duplicate webhook event ignored: {}", eventId);
                return;
            }

            // 4. Persist event before acknowledging Razorpay
            WebhookEvent webhookEvent = new WebhookEvent();

            webhookEvent.setEventId(eventId);
            webhookEvent.setEventType(eventType);
            webhookEvent.setRawPayload(
                    new String(rawBody, StandardCharsets.UTF_8));

            // once payment completed then mark the event status as received;
            webhookEvent.setStatus(WebhookEventStatus.RECEIVED);
            webhookEvent.setAttempts(0);

            webhookEventRepository.saveAndFlush(webhookEvent);

            log.info(
                    "Webhook event persisted successfully. Event ID: {}, Type: {}",
                    eventId,
                    eventType);

        } catch (JacksonException exception) {

            throw new BusinessException(
                    ErrorCode.WEBHOOK_EVENT_INVALID,
                    "Invalid webhook JSON payload");
        }
    }

    /**
     * Fetch the webhook event.
     * Check whether it has already been processed.
     * Extract Razorpay payment details.
     * Find the corresponding payment in MySQL.
     * Update payment status.
     * Create an Outbox event for Kafka.
     * Mark the webhook event as PROCESSED.
     * Commit all database changes in one transaction.
     */

    @Transactional
    public void processWebhookEvent(Long webhookEventId) {

        // 1. Fetch persisted webhook event
        WebhookEvent webhookEvent = webhookEventRepository
                .findById(webhookEventId)
                .orElseThrow(() -> new BusinessException(
                        ErrorCode.WEBHOOK_EVENT_INVALID,
                        "Webhook event not found: " + webhookEventId));

        // 2. Idempotency: Do not process an already processed event
        if (webhookEvent.getStatus() == WebhookEventStatus.PROCESSED) {
            log.info("Webhook event already processed: {}",
                    webhookEvent.getEventId());
            return;
        }

        try {

            // 3. Parse stored webhook JSON
            JsonNode root = objectMapper.readTree(
                    webhookEvent.getRawPayload());

            String eventType = webhookEvent.getEventType();

            // 4. Extract payment details
            JsonNode paymentEntity = root.path("payload")
                    .path("payment")
                    .path("entity");

            if (paymentEntity.isMissingNode() || !paymentEntity.isObject()) {
                throw new BusinessException(
                        ErrorCode.WEBHOOK_EVENT_INVALID,
                        "Payment details missing from webhook");
            }

            String orderId = paymentEntity.path("order_id").asText(null);
            String razorpayPaymentId = paymentEntity.path("id").asText(null);

            if (orderId == null || orderId.isBlank()) {
                throw new BusinessException(
                        ErrorCode.WEBHOOK_EVENT_INVALID,
                        "Razorpay order ID missing from webhook");
            }

            // 5. Find corresponding payment
            Payment payment = paymentRepository
                    .findByRazorpayOrderId(orderId)
                    .orElseThrow(() -> new BusinessException(
                            ErrorCode.PAYMENT_NOT_FOUND,
                            "Payment not found for Razorpay order ID: " + orderId));

            // 6. Prepare Kafka event
            Map<String, Object> kafkaEvent = new HashMap<>();

            kafkaEvent.put("paymentId", payment.getId());
            kafkaEvent.put("accountNumber", payment.getAccountNumber());
            kafkaEvent.put("amount", payment.getAmount());
            kafkaEvent.put(
                    "eventId",
                    "webhook:" + webhookEvent.getEventId());

            String topic;

            // 7. Handle successful payment
            if ("payment.captured".equals(eventType)) {

                if (payment.getStatus() == PaymentStatus.COMPLETED) {
                    log.info("Payment already completed: {}", payment.getId());

                    webhookEvent.setStatus(WebhookEventStatus.PROCESSED);
                    webhookEvent.setProcessedAt(Instant.now());
                    return;
                }

                payment.setRazorpayPaymentId(razorpayPaymentId);
                payment.setStatus(PaymentStatus.COMPLETED);

                topic = PAYMENT_COMPLETED_TOPIC;

                kafkaEvent.put("razorpayPaymentId", razorpayPaymentId);

            }

            // 8. Handle failed payment
            else if ("payment.failed".equals(eventType)) {

                // A completed payment must never become failed.
                if (payment.getStatus() == PaymentStatus.COMPLETED) {

                    log.info(
                            "Ignoring failed event because payment is already completed: {}",
                            payment.getId());

                    webhookEvent.setStatus(WebhookEventStatus.PROCESSED);
                    webhookEvent.setProcessedAt(Instant.now());
                    return;
                }

                if (payment.getStatus() == PaymentStatus.FAILED) {
                    webhookEvent.setStatus(WebhookEventStatus.PROCESSED);
                    webhookEvent.setProcessedAt(Instant.now());
                    return;
                }

                payment.setStatus(PaymentStatus.FAILED);
                payment.setPaymentFailureReason("Payment failed via Razorpay");

                topic = PAYMENT_FAILED_TOPIC;

                kafkaEvent.put("reason", payment.getPaymentFailureReason());
            } else {

                // Unsupported events are acknowledged without payment updates
                log.info("Ignoring unsupported webhook event: {}", eventType);

                webhookEvent.setStatus(WebhookEventStatus.PROCESSED);
                webhookEvent.setProcessedAt(Instant.now());
                return;
            }

            // 9. Save updated payment
            paymentRepository.save(payment);

            // 10. Create outbox event
            OutboxEvent outboxEvent = OutboxEvent.builder()
                    .eventId("webhook:" + webhookEvent.getEventId())
                    .topic(topic)
                    .messageKey(String.valueOf(payment.getId()))
                    .payload(objectMapper.writeValueAsString(kafkaEvent))
                    .status(OutboxStatus.PENDING)
                    .attempts(0)
                    .build();

            outboxEventRepository.save(outboxEvent);

            // 11. Mark webhook as processed
            webhookEvent.setStatus(WebhookEventStatus.PROCESSED);
            webhookEvent.setProcessedAt(Instant.now());

            webhookEventRepository.save(webhookEvent);

            log.info(
                    "Webhook processed successfully. Event ID: {}, Payment ID: {}",
                    webhookEvent.getEventId(),
                    payment.getId());

        } catch (JacksonException exception) {

            throw new BusinessException(
                    ErrorCode.WEBHOOK_EVENT_INVALID,
                    "Unable to parse stored webhook payload");
        }
    }

}
